export function getBike(slug: string): Bike | undefined {
  return bikes.find((b) => b.slug === slug);
}

export function bikeName(b: Pick<Bike, 'year' | 'make' | 'model'>): string {
  return `${b.year} ${b.make} ${b.model}`;
}

